// Generates small WebP thumbnails + inline blur previews for project images.
// Run after adding/changing a project image:  npm run thumbs
//
// Output:
//   public/projects/thumbs/<name>.webp       (480x270 16:9 crop, a few KB each)
//   components/home/project-thumbs.ts        (src + base64 blur per image)
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public", "projects", "thumbs");
const MAP_FILE = path.join(ROOT, "components", "home", "project-thumbs.ts");
const WIDTH = 480;

(async () => {
  const constants = fs.readFileSync(path.join(ROOT, "constants.ts"), "utf8");
  const images = [
    ...new Set(
      [...constants.matchAll(/^\s*image:\s*"(\/projects\/[^"]+)"/gm)].map((m) => m[1])
    ),
  ];
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const map = {};
  let total = 0;
  for (const img of images) {
    const srcPath = path.join(ROOT, "public", img);
    if (!fs.existsSync(srcPath)) {
      console.warn(`missing: ${img}`);
      continue;
    }
    const name = path.basename(img).replace(/\.[^.]+$/, "");
    const base = sharp(srcPath).rotate().flatten({ background: "#111111" });

    const thumb = await base
      .clone()
      .resize({ width: WIDTH, height: Math.round((WIDTH * 9) / 16), fit: "cover" })
      .webp({ quality: 55, effort: 6 })
      .toBuffer();
    fs.writeFileSync(path.join(OUT_DIR, `${name}.webp`), thumb);

    const blur = await base
      .clone()
      .resize({ width: 16, height: 9, fit: "cover" })
      .webp({ quality: 40 })
      .toBuffer();

    map[img] = {
      src: `/projects/thumbs/${name}.webp`,
      blur: `data:image/webp;base64,${blur.toString("base64")}`,
    };
    total += thumb.length;
    console.log(`${(thumb.length / 1024).toFixed(1)} KB  ${img}`);
  }

  const body =
    "// AUTO-GENERATED by scripts/make-project-thumbs.js — do not edit by hand.\n" +
    "// Run `npm run thumbs` after adding or changing a project image.\n" +
    "export const PROJECT_THUMBS: Record<string, { src: string; blur: string }> = " +
    JSON.stringify(map, null, 2) +
    ";\n";
  fs.writeFileSync(MAP_FILE, body);
  console.log(`\n${Object.keys(map).length} thumbs, ${(total / 1024).toFixed(0)} KB total`);
})();
